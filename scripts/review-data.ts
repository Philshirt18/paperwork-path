// Phase 1: load /data into Relate (WASM), check it, find circles per profile,
// and write docs/data-review.md for a human to review.
// Usage: node scripts/review-data.ts
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { initSync, RelateDb } from "@relate/relate-wasm";
import { seedStatements, validateData } from "../src/graph/seed.ts";

const require = createRequire(import.meta.url);
initSync({ module: readFileSync(require.resolve("@relate/relate-wasm/relate_bg.wasm")) });

const problems = validateData();
if (problems.length) {
  console.error("Data problems:\n" + problems.join("\n"));
  process.exit(1);
}

const db = new RelateDb();
const q = (query: string, params: Record<string, unknown> = {}) => {
  const env = JSON.parse(db.execute(query, JSON.stringify(params)));
  if (env.error) throw new Error(`${JSON.stringify(env.error)}\n${query}`);
  return env.rows as Record<string, any>[];
};
for (const s of seedStatements()) q(s.query, s.params);

const counts = q(`MATCH (n) WITH labels(n)[0] AS l, count(*) AS n RETURN l, n ORDER BY l`);
console.log("Loaded:", counts.map((c) => `${c.n} ${c.l}`).join(", "));

const profiles = q(`MATCH (p:Profile) RETURN p.id AS id, p.name AS name ORDER BY id`);
const lines: string[] = [];
lines.push("# Phase 1 — Data review", "");
lines.push("Generated by `node scripts/review-data.ts` from `data/*.json`. Sources read on 2026-11-27.", "");
lines.push("Legend: **official** = stated on the linked official page. *practice* = common in real life, not an official rule (drawn dashed in the app).", "");

lines.push("## Steps", "");
lines.push("| Step | Spanish | Requires — everyone | employee | autonomo | own_means | Source | Verified |");
lines.push("|---|---|---|---|---|---|---|---|");
const steps = q(`MATCH (s:Step) RETURN s.id AS id, s.name AS name, s.nameEs AS es, s.sourceUrl AS url, s.sourceTitle AS title, s.verified AS ok ORDER BY id`);
for (const s of steps) {
  const reqs = q(`MATCH (:Step {id:$id})-[r:REQUIRES]->(t:Step) RETURN t.id AS id, r.profiles AS profiles, r.basis AS basis`, { id: s.id });
  const fmt = (rs: typeof reqs) => rs.map((r) => (r.basis === "practice" ? `*${r.id}*` : r.id)).join(", ") || "—";
  const cell = (p: string) => fmt(reqs.filter((r) => (r.profiles as string[]).includes(p)));
  const src = s.url ? `[${s.title.split(" – ")[0]}](${s.url})` : "none";
  lines.push(`| **${s.id}** ${s.name} | ${s.es} | ${fmt(reqs.filter((r) => r.profiles.length === 0))} | ${cell("employee")} | ${cell("autonomo")} | ${cell("own_means")} | ${src} | ${s.ok ? "yes" : "**no**"} |`);
}

lines.push("", "## Circles found by the graph (per profile)", "");
for (const p of profiles) {
  const loops = q(
    `MATCH path = (s:Step)-[:REQUIRES*2..6]->(s)
     WHERE all(r IN relationships(path) WHERE size(r.profiles) = 0 OR $profile IN r.profiles)
     WITH [n IN nodes(path) | n.id] AS ids, [r IN relationships(path) | r.basis] AS bases
     RETURN ids, bases`,
    { profile: p.id },
  );
  // The same circle is found once per station on it; keep one copy.
  const seen = new Set<string>();
  const unique = loops.filter((l) => {
    const stations = (l.ids as string[]).slice(1);
    if (new Set(stations).size !== stations.length) return false; // figure-eight: two circles joined
    const key = [...stations].sort().join(",");
    return seen.has(key) ? false : (seen.add(key), true);
  });
  lines.push(`**${p.name}** (${p.id}): ${unique.length || "none"}`);
  for (const l of unique) {
    const ids = l.ids as string[];
    const ways = q(
      `UNWIND $ids AS id MATCH (w:Step)-[:WORKAROUND_FOR]->(:Step {id:id}) RETURN DISTINCT w.id AS id`,
      { ids },
    ).map((w) => w.id);
    const kind = (l.bases as string[]).every((b) => b === "official") ? "all official" : "includes practice";
    lines.push(`- ${ids.join(" → ")} (${kind}). Way out: ${ways.join(", ") || "none documented"}`);
  }
  lines.push("");
}

writeFileSync("docs/data-review.md", lines.join("\n") + "\n");
console.log(lines.slice(lines.indexOf("## Circles found by the graph (per profile)")).join("\n"));
